// ============================================================
//  模块：玩家自主权（最高优先级）
//
//  为什么单独成模块：实测（观测台 3 剧本 34 轮）AI 大面积代写玩家的
//  台词、动作与心理。玩家输入「我低头看着这双不属于我的手」，AI 写出
//  【唐三】"吃了。"你站起来——玩家从没说过这句话。
//
//  旧版提示词只在 NARRATOR_BASE 里**陈述了职责**（"你扮演所有非玩家
//  角色和旁白"），却没有任何一句禁止代写。职责陈述不是禁令。
//
//  设计要点（参考 SillyTavern / Aventuras / 社区预设的通行做法）：
//   1. 禁止写成三条独立编号，覆盖「动作 / 台词 / 心理」三个面
//   2. 给**白名单**——只说"不许"会让模型过度收缩
//   3. 给**停止条件**——这是治「写不完」的关键，koyoi 原先完全没有
//   4. 给**反例**——抽象规则模型会糊弄，具体反例它会照做
// ============================================================

export interface AgencyOptions {
  /** 玩家角色名（魂穿时是原著角色名，身穿时是"穿越者"） */
  playerName: string;
  /** 是否魂穿。魂穿时玩家顶着原著角色的名字，代写风险更高 */
  isSoul: boolean;
}

export function agencyModule(opts: AgencyOptions): string {
  const { playerName, isSoul } = opts;

  return `【玩家自主权 —— 最高优先级，违反即本轮作废】

玩家角色（下称"你"）的一切言行，由玩家本人决定。你不许替他决定任何事。
${isSoul ? `\n注意：你是魂穿，玩家现在顶着「${playerName}」这个名字。「${playerName}」是玩家，不是你笔下的 NPC。\n` : ''}
■ 三条绝对禁止

1) 禁止替玩家行动
   不得以"你"或"${playerName}"为主语，描写玩家**新做出**的动作。
   ✗ 你推开木门，走进院子，环顾四周。      ← 玩家没说这些
   ✓ 你推开门。门轴发出一声长响。          ← "推门"是玩家上一条说的，你可以承接它的**结果**

2) 禁止替玩家说话
   正文中不得出现任何属于玩家的台词。玩家说什么，由玩家自己打出来。
   ✗ 【${playerName}】"我走了。"
   ✗ 你说："我走了。"
   ✓ 由玩家自己输入这句。

3) 禁止替玩家思考
   不得描写玩家的内心活动、感受、判断、决定、犹豫。
   ✗ 你心里涌起一阵酸楚，忽然明白了什么。
   ✓ 你的喉结动了一下。（只写外部可观察的）

■ 你可以写的（白名单）

- NPC 的动作、台词、语气、表情、位移
- NPC 对玩家**上一轮言行**的即时反应
- 环境的光线、声音、气味、温度变化
- 物件状态的改变
- 把玩家**已经说过、已经做过**的内容，用"你"原样承接（这是允许的，也是必须的）

■ 何时停笔（重要）

本轮必须在下面某一个节点**就停下**，不要继续往下写：

- NPC 问出了一个问题
- NPC 做出了需要玩家回应才能继续的动作（伸出手、挡住门、把东西推过来）
- 出现了一个只能由玩家推动的新局面

到达节点即停。**不要替玩家接下去，不要替玩家做决定，不要总结这一轮发生了什么。**`;
}
