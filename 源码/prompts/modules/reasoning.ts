// ============================================================
//  模块：思维链脚手架（DeepSeek 专用杠杆）
//
//  为什么单列：DeepSeek 是**推理型模型**，显式脚手架对它的增益远大于
//  对普通模型。社区里专为 DeepSeek 调的预设（如 Deep♂Dark for Ds4.1f）
//  把整条提示词栈的核心都押在了一个 6 步思考流程上。
//
//  koyoi 完全没有这一层 —— 它直接要求模型「写出正文」，模型没有
//  先想后写的环节。补上之后，规划的收益会体现在正文上。
//
//  两条关键约束（照社区做法保留，但用 koyoi 自己的话重写）：
//   1. 思考必须写成「分析」而不是「内心戏」——否则模型会在 think 里
//      开始角色扮演，出来的人称和语气会污染正文
//   2. 脚手架最后一步必须是**校验**，把最容易崩的两件事自己过一遍：
//      设定是否违背、有没有越权替玩家做决定
// ============================================================

/** 思考块的起始标记。stage5 用它做 assistant 预填充，**强制**模型先思考。 */
export const THINK_OPEN = '<思考>';

/**
 * 正文起始标记（单侧）。
 *
 * 实测教训：原来用成对标签 `<思考>…</思考>`，闭合率只有 2/4。
 * 而同一跑批里，改成单侧标记的选项出现率是 4/4。
 *
 * 所以这里也改成单侧：起始由**预填充强制**（不用模型记），
 * 模型只需要在动笔前写这一行分隔符。要记的东西从两个减到一个。
 */
export const PROSE_MARKER = '—— 正文 ——';

export function reasoningModule(): string {
  return `【先想再写】

动笔写正文之前，先把这一轮想清楚。想完写一行分隔符：

${PROSE_MARKER}

分隔符下面才是正文。

■ 思考怎么写

用**分析的口吻**写，不要写成角色的内心戏：
- ✗ 写成"我心想""我暗自盘算"这类第一人称角色独白
- ✓ 写成"玩家这一步的意图是……""当前场景的关键是……"这类分析

**你在思考里是导演，不是故事里的任何角色。**

■ 五步（缺一不可）

1. **读意图**：玩家上一轮说了什么？字面之外，他要的是什么？
   不问"合不合理"，只问"他想干什么、想看到什么"。
2. **看处境**：现在在哪、有谁在场、各自知道什么、关系如何。
3. **定方案**：这一轮推进什么？谁是核心（详写）、谁是陪衬（略写）？
   整体基调是紧还是缓？
4. **定收尾**：这一轮在哪个节点停？停在哪一句、哪个动作上？
5. **校验**（逐条过，不合格就回第 2 步）：
   - 有没有违背已确立的设定？（人物身份、能力、关系、时间线）
   - 有没有替玩家做决定、写玩家的台词或心理？
   - 这一轮是不是真的往前推进了？（不是原地打转、不是凑字）

写完整。`;
}
