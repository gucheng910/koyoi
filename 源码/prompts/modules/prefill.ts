// ============================================================
//  模块：assistant 预填充（prefill）
//
//  这是从三个社区预设里学到的最有价值的一条 —— 它们的提示词栈
//  最末尾有一条 role=assistant 的短消息（如"--直出输出"），用它
//  **替模型起个头**，强制它接着往下写。
//
//  koyoi 原先完全没有这个东西。实测的对应症状：
//   - 格式漂移：【唐三】"..." 有时变成 唐三："..."
//   - 开头复述前情：每轮开头重申场景
//   - 破格式/前言废话
//
//  原理：把回复的**首 token 锁死**。模型只能顺着已给的开头续写，
//  没有位置去漂移或复述。
//
//  ⚠️ 实现要点：API 只返回**续写部分**，不含预填充本身。
//  所以 stage6 必须在拿到结果后把预填充前缀补回去，否则正文会
//  丢掉开头的【旁白】标记。
// ============================================================

/** 预填充内容。与 koyoi 既有的正文格式一致（绝大多数轮次以【旁白】开头）。 */
export const PREFILL_TEXT = '【旁白】';

/**
 * 是否把预填充作为最后一条 assistant 消息追加。
 * 关掉时完全不影响既有行为（消息列表结尾仍是玩家输入）。
 */
export function prefillModule(): string {
  return PREFILL_TEXT;
}
