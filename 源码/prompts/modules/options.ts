// ============================================================
//  模块：行动选项
//
//  koyoi 完全没有这个东西。玩家每轮读完之后只能自己想"我该干嘛"——
//  这在沉浸式 RP 里是真实的卡点：世界复杂、角色多、线索碎。
//
//  社区预设（狐神抚的"狐策"、Deep♂Dark 的"选项规则"）都把这件事
//  做成每轮固定产出，而且只给**玩家**的行动选项。
//
//  ⚠️ 实测教训（观测台 3 轮验证）：
//  最初用成对标签 `<选项>…</选项>`，模型把内容都写出来了，
//  但 **0/3 次写出闭合标签** `</选项>` —— 解析器完全抓不到。
//  同一个跑批里，`<思考>` 的闭合率是 2/3。
//
//  结论：**每多要求一个成对标记，模型对其他标记的遵守度就下降。**
//  所以这里改成**单侧标记**：只给一个起始分隔行，没有"要记得关"的东西。
//  少一半的契约，就少一半的失误点。
// ============================================================

/**
 * 单侧分隔标记。
 * 只有"开始"，没有"结束" —— 标记之后到文末的全部内容都算选项。
 */
export const OPTIONS_MARKER = '—— 你可以：';

export function optionsModule(): string {
  return `【行动选项】

正文写完之后，另起一行写上这一行：

${OPTIONS_MARKER}

然后下面用数字列出 3~4 个可选的下一步，一行为一个：

1. （一句话，具体到能做出来的动作或说出口的话）
2. （……）

■ 规则

- 选项必须**走向不同**：不能是同一件事的三种说法。至少有一个是主动推进、一个是不作为/观察、一个是意外的方向。
- 每个选项都要**具体可执行**——是玩家下一轮可以直接照着打的一句话。
- **只写玩家能做的事。** 不要写 NPC 会怎么做，不要把选项写成剧情预告。
- 不要剧透：选项里不能出现玩家此刻还不知道的信息。
- 选项只是给玩家参考，不是让他必须选。
- **不要在选项外面加任何标签或符号**，就写这一行分隔符加编号列表。`;
}
