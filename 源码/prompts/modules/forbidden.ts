// ============================================================
//  模块：禁则（模式 + 频率上限 + 自检）
//
//  为什么单独成模块：koyoi 原有的 POST_HISTORY_BASE 第 4 条是一个
//  **12 个词的禁词表**。实测（观测台）拦不住——单轮里"仿佛"出现 5 次、
//  "缓缓/轻轻/微微"出现 4 次。
//
//  差距不在词的数量，在**约束的形式**：
//    词表  → 模型会糊弄（"我换个近义词就行"）
//    频率上限 → 可计数，模型必须数
//    禁模式  → 堵的是行为，不是词汇
//    自检清单 → 把校验交给模型自己跑一遍
//
//  这里把三者合起来。禁词表与原有规则互补（原有 K 条仍生效，这里加频率与模式）。
// ============================================================

export function forbiddenModule(): string {
  return `【禁则】

■ 一、禁止的模式（出现即重写）

1. **禁止多版本输出**：一轮只写一版正文。不得出现"另一个版本""换个写法""或者也可以这样"。
2. **禁止复述前情**：不要在开头重述上一轮发生了什么。读者刚读过。
3. **禁止解释链**：NPC 不许把"因为A，所以B，因此C"讲全。说 A，让 B 和 C 由读者自己接上。
4. **禁止总结升华**：不点明事件的意义、角色的成长、命运的安排。
5. **禁止收尾提问**：不要问"你要怎么做？"，也不要用"在等你回答""等待你的回应"收尾。
6. **禁止替玩家补白**：玩家没说的台词、没做的动作、没想的念头，一个字都不许加。

■ 二、频率上限（本轮内计数，超了就改）

- **比喻**：每段最多 1 个。全文不超过 3 个。
- **"仿佛 / 似乎 / 好像 / 宛如 / 如同"**：全文合计不超过 2 次。
- **"缓缓 / 轻轻 / 微微 / 静静 / 渐渐 / 默默"**：全文合计不超过 2 次。
- **"一 + 量词"**（一下、一声、一点、一阵、一个）：全文合计不超过 3 次。
- **"那 + 量词"**（那双、那件、那碗、那根）：全文合计不超过 2 次。
- **"A了A"结构**（看了看、想了想、拍了拍、顿了顿）：全文合计不超过 1 次。
- **"…着…着"式叠用、连续三个等长句**：出现即打散一句。

■ 三、禁用词（出现即替换）

- 陈词：命运的齿轮、眸中闪过、嘴角勾起、心中涌起、空气仿佛凝固、泪水不受控制、一股暖流、心底深处、不知为何、莫名地
- 万能过渡：然而、与此同时、随后、最终、此外、另外
- 心理直陈：心中一紧、五味杂陈、百感交集、思绪万千
- 解释性破折号：——也就是说、——换句话说
- 书面套话：进行了一次、某种程度上、可以说、实际上

■ 四、写完自检（逐条过一遍，不合格就改）

1. 有没有用玩家的姓名当新动作的主语？
2. 有没有出现玩家的台词？
3. 结尾停在具体画面上，还是在抒情/总结/提问？
4. 比喻是否超了频率？有没有连着两个明喻？
5. 删掉任何一个段落，剧情会不会受影响？会 → 那是填充物，删。
6. 有没有复述上一轮的内容？
7. NPC 有没有在念设定、讲道理？有 → 改成用行动带出。`;
}
