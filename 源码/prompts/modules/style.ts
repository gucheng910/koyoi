// ============================================================
//  模块：文风（DeepSeek 版）
//
//  koyoi 原有的 ANTI_AI_PATTERN 是**禁词导向**的（"不要写 XX 词"）。
//  社区里专为 DeepSeek 调的预设走的是另一条路：**可执行的中文句法规则**
//  —— 它们不说"不要文绉绉"，而是给出具体的改写范例。
//
//  这里取其中最可操作的四条（都是中文写作的真实痛点）：
//   1. 修饰语前置（中文的"左分支"习惯）—— 附改前改后对照
//   2. 禁分句比喻（主句 + 逗号 + 像 XXX）
//   3. 禁五字以内过短对白
//   4. 禁连续并列短句写同一主体
//
//  另外保留那条最重要的判断标准：
//  "有美感的寡淡文字是坏文字，有情绪的通俗文字是好文字。"
// ============================================================

export function styleModule(): string {
  return `【文风】

■ 判断标准

**有美感的寡淡文字是坏文字，有情绪的通俗文字是好文字。**

不要追求文学性。不要拔高，不要炫技，不要为了好看而绕句。
文字直白、通俗、简练，情绪要满出来。

■ 四条硬规则

1) **修饰语前置**（中文的自然语序）
   ✗ 他笑着，笑得事不关己一样。      → ✓ 他事不关己地冷笑。
   ✗ 她对着潮水发呆，像是踏进了另一个世界。 → ✓ 她仿佛踏进了另一个世界，对着潮水发呆。

2) **禁止分句比喻**（主句 + 逗号 + 像 XXX）
   ✗ 她速度很快，像是不属于人类。    → ✓ 她速度快得不像人。

3) **禁止五字以内的过短对白**
   ✗ "嗯。"  ✗ "你笑了。"
   这类短对白要么删掉，要么并入相邻对白，让它承载信息。

4) **禁止连续并列短句写同一个主体**
   ✗ 他站着，没有动，也没晃。        → ✓ 他站着没有动。
   ✗ 暑假。第二天。很热。            → ✓ 暑假的第二天很热。

■ 其他

- 对白独立成段。
- 以长句为主，穿插短句；短句留给情绪高点。
- 有限视角：只写当前视角角色能感知到的东西。
- 环境够用就行，不要用环境填空。
- 禁止"不是……而是……"句式。`;
}
