// ============================================================
//  模块：篇幅控制
//
//  为什么单独成模块：旧版只有一句静态的"回复 200~400 字"。
//  实测后果（观测台）：同一模型、同一提示词，
//    身穿线 265~454 字（守规矩）
//    魂穿线 446 → 623 → 742 → 783 → … → 963 → 3261 字（崩溃）
//  而 3261 字那一轮，玩家的动作只有一句"回头看一眼圣魂村"——
//  没有事件、没有对话、没有推进，全是景物堆砌。
//
//  两个字面约束都不够：
//    1. 模型不数数，"200~400 字"它算不准 → 改用**段落数与场景档位**
//    2. 只给上限不给禁令，模型会用无关景物填满 → 必须**点名禁止填充物**
// ============================================================

export type LengthTier = 'brief' | 'normal' | 'heavy' | 'climax';

// 档位数值与 koyoi 原有的 POST_HISTORY_BASE（"回复 200~400 字"）对齐：
// 默认档 brief 就是 200~400，避免两条规则打架。
// 上一版我把 normal 设成 400~700，结果 A/B 里模块组平均 537 字、
// 对照组 310 字 —— 那不是"模块让输出变长"，是我给了它另一个目标，
// 对照被污染。默认必须与既有行为一致，往上的档位才是 opt-in。
const RANGE: Record<LengthTier, string> = {
  brief: '200~400 字',
  normal: '350~550 字',
  heavy: '500~750 字',
  climax: '700~1000 字',
};

export interface LengthOptions {
  tier?: LengthTier;
}

export function lengthModule(opts: LengthOptions = {}): string {
  const tier = opts.tier || 'brief';

  return `【篇幅】

本轮目标：**${RANGE[tier]}**（按剧情重要性自动微调，但不要突破档位上限太多）

■ 档位参考
- 日常推进、简单互动 → 200~400 字。几句话、一个动作交代清楚就停。
- 正常剧情推进     → 350~550 字。对话展开，反应到位。
- 关系变化、情绪堆积、有实质内容的互动 → 500~750 字。充分展开。
- 冲突爆发、重大转折 → 700~1000 字。用细节撑张力，不要急着收。

■ ⚠ 禁止用以下内容填充篇幅（出现即删）

- 天气、光线、气味的**独立成段**描写
- 家具、陈设、建筑材质的逐项罗列
- 路程经过（"走了很久""转过一道坡""又走了约莫一炷香"）
- 换装、吃饭、杂务的完整过程
- 无意义的等待、重复的同一个动作
- 复述前文已经交代过的信息
- 景物描写用来开头或收尾（除非时间地点真的变了）

**字数不够时，深化当前正在进行的对话与反应，不要另起一段无关景物。**

⚠ 篇幅只算**正文**。标了"—— 你可以："之后的行动选项、以及思考过程，**都不计入**。
不要因为有选项就压缩正文，也不要为了凑字数把正文里的对话稀释掉。

■ 自检
写完回头看一眼：删掉任何一个段落，剧情是否受影响？
不受影响的段落就是填充物，删掉。`;
}
