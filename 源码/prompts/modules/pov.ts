// ============================================================
//  模块：叙事人称
//
//  为什么单独成模块：koyoi 原先的提示词里**从头到尾没有声明过用第几人称**。
//  实测后果：开场严格遵守第二人称"你"，正文立刻切成第三人称——
//  「唐三低头看向自己的手」。玩家看到自己的角色被当成一个外人来写。
//
//  这不是模型的错，是提示词没说。SillyTavern / Aventuras / 社区预设
//  三家都把"人称"做成一个独立可选项，且都带反例。
// ============================================================

export type Pov = 'second' | 'third';

export interface PovOptions {
  pov: Pov;
  /** 玩家角色名（第三人称模式下会用到） */
  playerName: string;
}

export function povModule(opts: PovOptions): string {
  const { pov, playerName } = opts;

  if (pov === 'third') {
    return `【叙事人称 —— 第三人称，全程不得切换】

本轮一律使用第三人称。玩家角色称「${playerName}」或"他/她"。

■ 反例（禁止）
✗ 你推开门。                      ← 第三人称模式下不得出现"你"
✗ 你低头看向自己的手。

■ 正例
✓ ${playerName}推开门。
✓ 他低头看向自己的手。

■ 边界
- 可以写玩家角色**已经做出**的动作（用第三人称转述）
- 仍然不得写玩家的新动作、台词、心理（见【玩家自主权】）`;
  }

  return `【叙事人称 —— 第二人称，全程不得切换】

本轮一律使用第二人称。玩家角色**只称"你"**。

■ 反例（禁止）
✗ ${playerName}低头看向自己的手。      ← 用姓名指代玩家
✗ 他推开门，走进院子。                  ← 用第三人称指代玩家
✗ ${playerName}："我走了。"              ← 用姓名标注玩家的台词

■ 正例
✓ 你低头看向自己的手。
✓ 你推开门。门轴发出一声长响。
✓ 她看着你，没有立刻说话。（NPC 用"她"，玩家用"你"）

■ 边界
- NPC 用姓名或"他/她"
- 叙述只写"你"所在位置能看到、听到、闻到、碰到的东西
- 开场与之后的每一轮**必须保持同一人称**，不得因为轮次增加而漂移`;
}
