// ============================================================
//  模块：完整性（防截断）
//
//  实测：一次 A/B 里出现过"输出 0 字"的轮次；更早的 gemini 跑批里
//  也有输出被截在半句的情况。koyoi 侧有流式超时兜底（30s 无数据会
//  交付已收到的部分），但**提示词层面**没有要求模型写完整。
//
//  这条成本极低（几十字），但能减少"写到一半断了"这类硬伤。
// ============================================================

export function truncationModule(): string {
  return `【完整性】

把本轮内容写完再停。到达自然结尾之前，不要在中间停下。

如果写到一半感觉"这里好像可以收了"，说明还没收对——继续写到 agency 模块规定的那个停止点（NPC 发问 / 等待回应的动作 / 新局面）为止。

不要用省略号草草收尾。不要只写半句就断。`;
}
