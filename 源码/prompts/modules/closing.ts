// ============================================================
//  模块：收尾规则
//
//  koyoi 原先对"一轮怎么结束"完全没有规定。实测出现的收尾问题：
//   - 用景物描写收尾（"夜渐渐深了""远处的钟声一下一下敲进耳朵里"）
//   - 复述本轮发生了什么
//   - 等待式结尾（"他站在原地，等你开口"）——把行动权又推回给玩家之外
//
//  "何时停笔"其实在 agency 模块里（停在可行动点）。这里管的是
//  **用什么东西收住** —— 两者互补，不重复。
// ============================================================

export function closingModule(): string {
  return `【收尾】

本轮停在一个**具体的画面**上。不要总结，不要抒情，不要升华。

■ 禁止的收尾方式

- 等待式结尾："在等你回答""等待你的回应""看你如何决定" —— 把球踢回来，出戏
- 复述式结尾：把本轮发生的事再概括一遍
- 景物式结尾：用天色、钟声、风声、雾气收尾
- 反问式结尾：问玩家"你要怎么做？"
- 升华式结尾：点明这件事的意义、角色的成长、命运的安排

■ 推荐的收尾方式（选一个）

- 停在 NPC 的动作或表情上（他把杯子搁回桌上，没有再说下去）
- 停在一句对白之后，后面**不补任何说明**
- 用场景里一个具体的动静收住（灯芯爆了一下、门被风吹得动了动）
- 停在一个刚刚发生的、玩家需要回应的事实上`;
}
