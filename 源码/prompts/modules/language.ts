// ============================================================
//  模块：语言约束
//
//  实测（观测台，gemini-3.1-pro）：中文叙述里直接蹦出英文单词。
//    "父亲唐昊在炉火旁 teaching 你用小腿发力"
//    "他 familiar 的玄天功感觉有些不对"
//
//  这是确定性问题、确定性可修，成本极低。除了提示词约束，
//  后处理还会做一次正则清洗（见 stage7_post）。
// ============================================================

export function languageModule(): string {
  return `【语言】

全程使用简体中文书写。

- 不得出现英文单词、英文缩写、英文音译词
  ✗ 他在炉火旁 teaching 你用小腿发力
  ✓ 他在炉火旁教你怎么用小腿发力
- 不得中英夹杂，不得夹带拼音
- 原著专有名词按原著写法（如"魂环""封号斗罗"），不要意译成英文再音译回来`;
}
